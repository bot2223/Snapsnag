import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export type ReportLang = "en" | "de";

type CompanyInfo = {
  name: string | null;
  address: string | null;
  phone: string | null;
  /** Base64 data URL (data:image/jpeg;base64,...) or null if no logo/couldn't load it. */
  logoDataUrl: string | null;
  /** Only passed when the manager is on Business plan — otherwise report stays plain black/white. */
  brandColor: string | null;
};

type ReportStats = {
  total: number;
  resolved: number;
  slaCompliance: number;
};

type SnagRow = {
  location: string;
  category: string;
  priority: string;
  status: string;
  created_at: string;
  deadline_at: string | null;
  description: string;
  notes: string | null;
  assignedTo: string | null;
  /** Pre-resolved base64 data URLs — the generator never fetches anything itself. */
  beforePhotoDataUrl: string | null;
  afterPhotoDataUrl: string | null;
};

// Report-only strings — separate from the app's UI i18n files since these
// never appear in the app itself, only inside the generated document.
